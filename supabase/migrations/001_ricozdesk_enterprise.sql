-- In-app notification events for the main hand-offs.
create or replace function public.notify_ticket_created()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.notifications(user_id, ticket_id, title, body)
  select p.id, new.id, 'New customer ticket', 'A new ' || new.source || ' ticket #' || new.ticket_number || ' has been recorded.'
  from public.profiles p
  where p.is_active = true and p.role in ('admin', 'support_manager');
  return new;
end $$;

create or replace function public.notify_ticket_handoff()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if new.tech_owner_id is not null and new.tech_owner_id is distinct from old.tech_owner_id then
    insert into public.notifications(user_id, ticket_id, title, body)
    values (new.tech_owner_id, new.id, 'New issue assigned', 'Ticket #' || new.ticket_number || ' has been assigned to you.');
  end if;
  if new.status = 'Fix Ready' and old.status is distinct from new.status and new.support_owner_id is not null then
    insert into public.notifications(user_id, ticket_id, title, body)
    values (new.support_owner_id, new.id, 'Fix ready for verification', 'Engineering marked ticket #' || new.ticket_number || ' as Fix Ready. Please verify with the customer.');
  end if;
  return new;
end $$;

