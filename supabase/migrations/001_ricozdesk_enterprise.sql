create or replace function public.current_ricozdesk_role()
returns text language sql stable security definer set search_path = public
as $$ select role::text from public.profiles where id = auth.uid() and is_active = true limit 1 $$;

create or replace function public.is_ricozdesk_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select coalesce(public.current_ricozdesk_role() = 'admin', false) $$;

create or replace function public.can_read_ticket(p_ticket_id uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.tickets t
    where t.id = p_ticket_id and (
      public.current_ricozdesk_role() = 'admin'
      or public.current_ricozdesk_role() = 'support_manager'
      or (public.current_ricozdesk_role() = 'support_agent' and (t.support_owner_id = auth.uid() or t.created_by = auth.uid()))
      or (public.current_ricozdesk_role() = 'tech_lead' and t.assigned_team = 'Engineering')
      or (public.current_ricozdesk_role() = 'developer' and t.tech_owner_id = auth.uid())
    )
  )
$$;

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$ begin new.updated_at = now(); return new; end $$;

create or replace function public.set_ticket_sla_deadlines()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  v_first numeric;
  v_resolution numeric;
begin
  select first_response_hours, resolution_hours into v_first, v_resolution
  from public.sla_policies where priority = new.priority;
  if v_first is null then
    v_first := case new.priority when 'Critical' then 0.25 when 'High' then 0.5 when 'Medium' then 4 else 8 end;
  end if;
  if v_resolution is null then
    v_resolution := case new.priority when 'Critical' then 2 when 'High' then 8 when 'Medium' then 24 else 48 end;
  end if;
  if tg_op = 'UPDATE' and new.priority is distinct from old.priority then
    if new.first_responded_at is null then
      new.first_response_due_at := now() + make_interval(secs => (v_first * 3600)::double precision);
    end if;
    if new.resolved_at is null then
      new.sla_due_at := now() + make_interval(secs => (v_resolution * 3600)::double precision);
    end if;
  else
    if new.first_response_due_at is null then new.first_response_due_at := now() + make_interval(secs => (v_first * 3600)::double precision); end if;
    if new.sla_due_at is null then new.sla_due_at := now() + make_interval(secs => (v_resolution * 3600)::double precision); end if;
  end if;
  return new;
end $$;

create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles(id, full_name, email, role, team)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)), new.email, 'support_agent', 'Customer Support')
  on conflict (id) do update set email = excluded.email;
  return new;
end $$;

