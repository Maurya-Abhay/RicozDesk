create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text not null unique,
  role public.ricozdesk_role not null default 'support_agent',
  team text not null default 'Customer Support',
  skills text[] not null default '{}',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.teams (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  team_type text not null check (team_type in ('Support', 'Engineering', 'Management')),
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.websites (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  url text not null unique,
  status text not null default 'Active' check (status in ('Active', 'Inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sla_policies (
  priority text primary key check (priority in ('Critical', 'High', 'Medium', 'Low')),
  first_response_hours numeric(8,2) not null check (first_response_hours > 0),
  resolution_hours numeric(8,2) not null check (resolution_hours > 0 and resolution_hours >= first_response_hours),
  updated_by uuid references public.profiles(id),
  updated_at timestamptz not null default now()
);

insert into public.sla_policies(priority, first_response_hours, resolution_hours) values
  ('Critical', 0.25, 2), ('High', 0.5, 8), ('Medium', 4, 24), ('Low', 8, 48)
on conflict (priority) do nothing;

create table if not exists public.tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  title text not null,
  description text not null,
  customer_name text not null,
  customer_email text,
  customer_phone text,
  source public.ticket_source not null,
  email_subject text,
  website_id uuid not null references public.websites(id),
  category text not null default 'General Support',
  module text not null default 'Other',
  priority text not null default 'Medium' check (priority in ('Critical', 'High', 'Medium', 'Low')),
  status text not null default 'New' check (status in ('New', 'Under Review', 'Assigned', 'In Progress', 'Waiting', 'Fix Ready', 'Verification', 'Reopened', 'Resolved', 'Closed')),
  assigned_team text not null default 'Customer Support' check (assigned_team in ('Customer Support', 'Engineering')),
  support_owner_id uuid references public.profiles(id) on delete set null,
  tech_owner_id uuid references public.profiles(id) on delete set null,
  created_by uuid not null references public.profiles(id),
  affected_url text,
  environment text,
  browser_device text,
  first_response_due_at timestamptz,
  first_responded_at timestamptz,
  sla_due_at timestamptz,
  resolved_at timestamptz,
  escalated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ticket_comments (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  user_id uuid not null references public.profiles(id),
