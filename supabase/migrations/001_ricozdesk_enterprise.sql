-- Enforce column-level role boundaries in addition to row-level policies.
create or replace function public.guard_ticket_update_by_role()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  v_role text := public.current_ricozdesk_role();
begin
  if v_role = 'admin' then return new; end if;

  if v_role = 'support_manager' then
    if (to_jsonb(new) - array['status','priority','support_owner_id','assigned_team','escalated_at','resolved_at','updated_at'])
       is distinct from
       (to_jsonb(old) - array['status','priority','support_owner_id','assigned_team','escalated_at','resolved_at','updated_at']) then
      raise exception 'Support Manager cannot edit customer or technical ticket content.';
    end if;
    if new.status is distinct from old.status and new.status not in ('Under Review','Waiting','Verification','Resolved','Closed','Reopened') then
      raise exception 'Support Manager cannot set this ticket status.';
    end if;
  elsif v_role = 'support_agent' then
    if (to_jsonb(new) - array['status','resolved_at','updated_at'])
       is distinct from (to_jsonb(old) - array['status','resolved_at','updated_at']) then
      raise exception 'Support Agent can only update ticket status.';
    end if;
    if new.status is distinct from old.status and new.status not in ('Under Review','Waiting','Verification','Resolved','Closed','Reopened') then
      raise exception 'Support Agent cannot set this ticket status.';
    end if;
  elsif v_role = 'tech_lead' then
    if (to_jsonb(new) - array['status','priority','tech_owner_id','assigned_team','escalated_at','resolved_at','updated_at'])
       is distinct from
       (to_jsonb(old) - array['status','priority','tech_owner_id','assigned_team','escalated_at','resolved_at','updated_at']) then
      raise exception 'Development Lead cannot edit customer ticket content.';
    end if;
    if new.status is distinct from old.status and new.status not in ('Assigned','In Progress','Waiting','Fix Ready') then
      raise exception 'Development Lead cannot set this ticket status.';
    end if;
  elsif v_role = 'developer' then
    if (to_jsonb(new) - array['status','resolved_at','updated_at'])
       is distinct from (to_jsonb(old) - array['status','resolved_at','updated_at']) then
      raise exception 'Developer can only update progress status.';
    end if;
    if new.status is distinct from old.status and new.status not in ('In Progress','Waiting','Fix Ready') then
      raise exception 'Developer cannot set this ticket status.';
    end if;
  else
    raise exception 'Your account does not have permission to update tickets.';
  end if;
  return new;
end $$;

drop trigger if exists tickets_guard_update_by_role on public.tickets;
create trigger tickets_guard_update_by_role before update on public.tickets
for each row execute procedure public.guard_ticket_update_by_role();

create or replace function public.guard_comment_visibility()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if public.current_ricozdesk_role() in ('developer', 'tech_lead') and new.visibility = 'Customer' then
    raise exception 'Technical team comments are internal only.';
  end if;
  return new;
end $$;

